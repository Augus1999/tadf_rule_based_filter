"""
Rule-based filters to clean the TADF-type OLED emittor molecules generated by ChemBFN model.
"""

from rdkit import RDLogger
from rdkit.Chem import MolFromSmiles, CanonSmiles, AddHs, Draw

RDLogger.DisableLog("rdApp.*")  # type: ignore


sample_file = "YOUR/SAMPLE/FILE.csv"
source_file = "YOUR/SOURCE/FILE.csv"
excluded_elements = []  # unwanted elements

if __name__ == "__main__":
    with open(source_file, "r", encoding="utf-8") as f:
        source = f.readlines()
    _tag_idx = []
    for idx, _tag in enumerate(source[0].replace("\n", "").split(",")):
        if _tag.lower() in ("smiles", "safe"):
            _tag_idx.append(idx)
    source = list(set([CanonSmiles(i.split(",")[_tag_idx[0]]) for i in source[1:]]))
    with open(sample_file, "r", encoding="utf-8") as f:
        samples = f.readlines()
    # --- filter out the invalide SMILES strings ---
    samples = [
        CanonSmiles(i.replace("\n", ""))
        for i in samples
        if i.replace("\n", "") and MolFromSmiles(i.replace("\n", ""))
    ]
    # --- filter out the duplicated and disconnected molecules ---
    samples = [i for i in list(set(samples)) if ("." not in i) and (i not in source)]
    # --- filter out the unwanted elements ---
    samples = [i for i in samples if all(j not in i for j in excluded_elements)]
    samples_ = []
    for sample in samples:
        sample_ = MolFromSmiles(sample)
        sample_ = AddHs(sample_)
        mwt = sample_.GetNumHeavyAtoms()
        ring_info = sample_.GetRingInfo().AtomRings()
        # --- filter out molecules without clear donor-accepter structure ---
        if mwt < 16 or len(ring_info) < 3:
            continue
        # --- filter out molecules with too many single bonds ---
        rigid = True
        for atom in sample_.GetAtoms():
            if not atom.GetIsAromatic():
                if atom.GetAtomicNum() == 1:
                    continue
                if atom.GetTotalNumHs() >= 1 or atom.GetAtomicNum() == 6:
                    rigid = False
        # --- filter out molecules with unsuiatble ring sizes ---
        if rigid and all([4 < len(i) <= 6 for i in ring_info]):
            samples_.append(sample)
    print(f"{(c := len(samples_))} {"candidates" if c > 1 else "candidate"} obtained.")
    with open(sample_file.replace(".csv", "_filtered.csv"), "w", encoding="utf-8") as g:
        g.write("\n".join(samples_))
    svg = Draw._MolsToGridSVG([MolFromSmiles(s) for s in samples_], 6, (400, 200))
    with open(sample_file.replace(".csv", "_filtered.svg"), "w") as g:
        g.write(svg)
